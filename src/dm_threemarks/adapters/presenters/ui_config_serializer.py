# -*- coding: utf-8 -*-
from __future__ import absolute_import


class UiConfigSerializer(object):
    """Serializes ConfigStore settings into lightweight Gameface JSON UI blocks."""

    def __init__(self, config_store):
        self._config = config_store

    def v3_ui_payload(self, cfg=None):
        c = self._config
        return {
            'fnt': c.integer('v3Font', 0, 7, cfg),
            'den': c.integer('v3Density', 0, 2, cfg),
            'minW': c.integer('v3MinWidth', 0, 200, cfg),
            'anc': c.integer('v3Anchor', 0, 5, cfg),
            'fs': c.integer('v3FrameStyle', 0, 3, cfg),
            'rad': c.integer('v3Radius', 0, 14, cfg),
            'cc': c.color('v3CornerColor', cfg),
            'ca': round(c.number('v3CornerAlpha', 0.0, 1.0, cfg), 3),
            'ba': round(c.number('v3BorderAlpha', 0.0, 1.0, cfg), 3),
            'bgc': c.color('v3BgColor', cfg),
            'bgo': round(c.number('v3BgOpacity', 0.0, 1.0, cfg), 3),
            'sp': c.integer('v3StarsPos', 0, 5, cfg),
            'ss': c.integer('v3StarsStyle', 0, 2, cfg),
            'sd': bool((cfg if cfg is not None else c).get('v3StarsDivider', False)),
            'sz': c.integer('v3StarsSize', 10, 22, cfg),
            'sg': c.integer('v3StarsGap', 2, 14, cfg),
            'sgl': bool((cfg if cfg is not None else c).get('v3StarsGlow', True)),
            'son': c.color('v3StarOnColor', cfg),
            'sof': c.color('v3StarOffColor', cfg),
            'ho': c.integer('v3HeaderOrder', 0, 2, cfg),
            'dec': c.integer('v3PctDecimals', 0, 1, cfg),
            'di': c.integer('v3DeltaIcon', 0, 3, cfg),
            'dc': c.integer('v3DeltaColorMode', 0, 1, cfg),
            'bs': c.integer('v3BarStyle', 0, 3, cfg),
            'bsc': c.integer('v3BarScale', 0, 1, cfg),
            'bh': c.integer('v3BarHeight', 2, 10, cfg),
            'bth': c.integer('v3BarTrackHeight', 1, 10, cfg),
            'bt': c.string('v3BarCustomText', u'KIBERSPORT', 24, cfg) or u'KIBERSPORT',
            'bts': c.integer('v3BarTextSize', 10, 26, cfg),
            'bet': bool((cfg if cfg is not None else c).get('v3BarEndTicks', True)),
            'bcur': bool((cfg if cfg is not None else c).get('v3BarCursor', True)),
            'bmk': bool((cfg if cfg is not None else c).get('v3BarMarks', False)),
            'bcm': c.integer('v3BarColorMode', 0, 2, cfg),
            'bcc': c.color('v3BarCustomColor', cfg),
            'dmgOn': bool((cfg if cfg is not None else c).get('v3ShowDamage', True)),
            'dl': c.integer('v3DamageLabel', 0, 3, cfg),
            'dlc': c.string('v3DamageCustomLabel', u'Сум. урон', 24, cfg),
            'sep': c.integer('v3ThousandsSep', 0, 2, cfg),
            'ddyn': bool((cfg if cfg is not None else c).get('v3DamageDynColor', True)),
            'ash': c.integer('v3AssistShow', 0, 3, cfg),
            'am': c.integer('v3AssistMode', 0, 1, cfg),
            'ap': c.integer('v3AssistPlace', 0, 1, cfg),
            'ahz': bool((cfg if cfg is not None else c).get('v3AssistHideZero', False)),
            'asz': c.integer('v3AssistSize', 0, 24, cfg),
            'tsh': c.integer('v3TempoShow', 0, 3, cfg),
            'tmm': c.integer('v3TempoMode', 0, 2, cfg),
            'tp': c.integer('v3TempoPlace', 0, 1, cfg),
            'tsz': c.integer('v3TempoSize', 0, 24, cfg),
            'up': c.color('v3AccentPlus', cfg),
            'dn': c.color('v3AccentMinus', cfg),
            'zr': c.color('v3AccentZero', cfg),
            'big': c.color('v3AccentBig', cfg),
            'tm': c.color('v3TextMain', cfg),
            'tmu': c.color('v3TextMuted', cfg),
            'hThr': True,
            'h100': True,
        }

    def vh_ui_payload(self, cfg=None):
        c = self._config
        src = cfg if cfg is not None else c
        return {
            'fnt': c.integer('vhFont', 0, 7, cfg),
            'den': c.integer('vhDensity', 0, 2, cfg),
            'minW': 0,
            'anc': 0,
            'fs': c.integer('vhFrameStyle', 0, 3, cfg),
            'rad': c.integer('vhRadius', 0, 14, cfg),
            'cc': c.color('vhCornerColor', cfg),
            'ca': round(c.number('vhCornerAlpha', 0.0, 1.0, cfg), 3),
            'ba': round(c.number('vhBorderAlpha', 0.0, 1.0, cfg), 3),
            'bgc': c.color('vhBgColor', cfg),
            'bgo': round(c.number('vhBgOpacity', 0.0, 1.0, cfg), 3),
            'sp': c.integer('vhStarsPos', 0, 5, cfg),
            'ss': c.integer('vhStarsStyle', 0, 2, cfg),
            'sd': bool(src.get('vhStarsDivider', False)),
            'sz': c.integer('vhStarsSize', 10, 22, cfg),
            'sg': c.integer('vhStarsGap', 2, 14, cfg),
            'sgl': bool(src.get('vhStarsGlow', True)),
            'son': c.color('vhStarOnColor', cfg),
            'sof': c.color('vhStarOffColor', cfg),
            'ho': 0,
            'dec': c.integer('vhPctDecimals', 0, 1, cfg),
            'di': 3,
            'dc': 0,
            'bs': c.integer('vhBarStyle', 0, 3, cfg),
            'bsc': c.integer('vhBarScale', 0, 1, cfg),
            'bh': c.integer('vhBarHeight', 2, 10, cfg),
            'bth': c.integer('vhBarTrackHeight', 1, 10, cfg),
            'bt': c.string('vhBarCustomText', u'KIBERSPORT', 24, cfg) or u'KIBERSPORT',
            'bts': c.integer('vhBarTextSize', 10, 26, cfg),
            'bet': bool(src.get('vhBarEndTicks', True)),
            'bcur': bool(src.get('vhBarCursor', True)),
            'bmk': bool(src.get('vhBarMarks', False)),
            'bcm': 2,
            'bcc': c.color('vhBarColor', cfg),
            'dmgOn': bool(src.get('vhShowEma', True)),
            'dl': 0,
            'dlc': u'Суммарный урон',
            'sep': c.integer('vhThousandsSep', 0, 2, cfg),
            'ddyn': True,
            'ash': 3,
            'am': 0,
            'ap': 0,
            'ahz': False,
            'asz': 0,
            'tsh': 3,
            'tmm': 0,
            'tp': 0,
            'tsz': 0,
            'up': c.color('v3AccentPlus', cfg),
            'dn': '#E57373',
            'zr': '#9AA3AE',
            'big': '#B07CFF',
            'tm': c.color('vhTextMain', cfg),
            'tmu': c.color('vhTextMuted', cfg),
            'hThr': bool(src.get('vhShowThresholds', True)),
            'h100': True,
        }

    def ui_payload(self):
        c = self._config
        preset = c.integer('battlePreset', 0, 1)
        return {
            's': round(c.ui_scale(), 3),
            'hs': round(c.vh_scale(), 3),
            'preset': preset,
            'bg': round(c.number('bgOpacity', 0.0, 1.0), 3),
            'alpha': round(c.number('panelOpacity', 0.0, 1.0), 3),
            'onlyPct': bool(preset == 1 or c.get('battlePercentOnly', False)),
            'up': c.color('colorPlus'),
            'dn': c.color('colorMinus'),
            'zr': c.color('colorZero'),
            'bUp': c.color('barColorPlus'),
            'bDn': c.color('barColorMinus'),
            'bZr': c.color('barColorZero'),
            'bH': c.color('barColorHangar'),
            'bSign': bool(c.get('barBySign', True)),
            'bStd': c.color('barColorStandard'),
            'trk': round(c.number('trackOpacity', 0.0, 1.0), 3),
            'tick': c.color('tickColor'),
            'pct': c.color('pctColor'),
            'pctSign': bool(c.get('pctFollowsSign', False)),
            'glow': bool(c.get('glow', True)),
            'band': round(c.number('zeroBand', 0.0, 5.0), 3),
            'big': c.color('colorBig'),
            'bBig': c.color('barColorBig'),
            'bigFrom': round(c.number('bigFrom', 0.0, 100.0), 3),
            'bigDmg': bool(c.get('bigByDamage', True)),
            'dmgSign': bool(c.get('dmgFollowsSign', True)),
            'dmg': c.color('colorDmg'),
            'proj': c.color('colorProj'),
            'v3': self.v3_ui_payload() if preset == 0 else {'fnt': c.integer('v3Font', 0, 7)},
            'vh': self.vh_ui_payload(),
        }
